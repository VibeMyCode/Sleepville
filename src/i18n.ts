// each language under its own name, in the order the language switch lists them
export const LANG_NAMES = {
  en: 'English',
  de: 'Deutsch',
  es: 'Español',
  fr: 'Français',
  it: 'Italiano',
  pt: 'Português',
  tr: 'Türkçe',
  id: 'Indonesia',
  ru: 'Русский',
  zh: '中文',
  ja: '日本語',
  ko: '한국어',
}
export type Lang = keyof typeof LANG_NAMES
// every language is checked against the full key set above; lookups by sound or mix id stay loose
export type Strings = Omit<typeof ru, 'sounds' | 'presets'> & { sounds: Record<string, string>; presets: Record<string, string> }
export const STRINGS: Record<Lang, Strings> = { en, de, es, fr, it, pt, tr, id, ru, zh, ja, ko }

// the first of the system's languages the app speaks; Android can still report Indonesian by its old code "in"
export const pickLang = (tags: readonly string[]): Lang => {
  for (const tag of tags) {
    const l = tag.toLowerCase().split(/[-_]/)[0].replace(/^in$/, 'id')
    if (l in STRINGS) return l as Lang
  }
  return 'en'
}
export const detectLang = () => pickLang(navigator.languages)

export const I18n = createContext<Strings>(ru)
export const useT = () => useContext(I18n)
